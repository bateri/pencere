-- The browser page: a browser the host keeps, driven as a person drives the page, and told what its
-- engine would tell it (the host with no screen has no engine).

local test = require("pencere.test")
local expect = test.expect

local function open(options)
	options = options or {}
	options.calls = {}
	options.size = { 900, 600 }
	return test.open(options)
end

test("the page's browser is a room, a browser to a screen reader, and asks nothing before it is ready", function()
	local page = open()
	local rooms = page:browsers()
	expect(#rooms):to_be(1)
	expect(rooms[1].profile):to_be("browser-lua")
	expect(rooms[1].windows):to_be("page")
	expect(rooms[1].keys[1]):to_be("cmd+l")
	expect(#rooms[1].keys):to_be(5)
	expect(rooms[1].w > 100 and rooms[1].h > 100):to_be_truthy()
	expect(page:get_by_role("browser"):count()):to_be(1)
	expect(page:get_by_id("web"):navigations()):to_equal({})
end)

test("it goes to its first address when the browser says it is ready, and the address line follows it", function()
	local page = open()
	local web = page:get_by_id("web")
	web:say({ status = "starting", message = "The browser is starting." })
	expect(web:navigations()):to_equal({})
	expect(page:says("The browser is starting.")):to_be_truthy()
	web:say({ status = "ready" })
	expect(web:navigations()):to_equal({ { go = "https://example.com/" } })
	web:say({ url = "https://example.com/", title = "Example Domain" })
	-- Told again, it does not go again.
	expect(#web:navigations()):to_be(1)
	expect(page:field("address")):to_be("https://example.com/")
	expect(page:says("Example Domain")):to_be_truthy()
end)

test("an address typed is gone to as a web address, and the buttons ask for what they say", function()
	local page = open()
	local web = page:get_by_id("web")
	web:say({ status = "ready" })
	page:get_by_id("address"):fill("example.org/docs")
	page:press("enter")
	expect(web:navigations()[2]):to_equal({ go = "https://example.org/docs" })
	web:say({ url = "https://example.org/docs", title = "Docs", back = true, loading = true })
	page:get_by_role("button", { name = "Stop" }):click()
	expect(web:navigations()[3]):to_equal({ command = "stop" })
	web:say({ url = "https://example.org/docs", title = "Docs", back = true })
	page:get_by_role("button", { name = "Back" }):click()
	expect(web:navigations()[4]):to_equal({ command = "back" })
	page:get_by_role("button", { name = "Reload" }):click()
	expect(web:navigations()[5]):to_equal({ command = "reload" })
end)

test("an address of a kind a browser does not go to is not given to it, and the page says so", function()
	local page = open()
	local web = page:get_by_id("web")
	web:say({ status = "ready" })
	page:get_by_id("address"):fill("file:///etc/passwd")
	page:press("enter")
	expect(#web:navigations()):to_be(1)
	expect(page:says("http, https, about:blank and data: addresses only")):to_be_truthy()
end)

test("a failed load is the page's to say, and a status the page does not know is a browser that is not ready", function()
	local page = open()
	local web = page:get_by_id("web")
	web:say({ status = "ready", url = "https://example.com/" })
	web:say({ url = "https://nowhere.test/", error = { url = "https://nowhere.test/", code = -105, message = "The address was not found." } })
	expect(page:says("Could not load https://nowhere.test/: The address was not found.")):to_be_truthy()
	web:say({ status = "warming", message = "A word a later host says." })
	expect(page:says("A word a later host says.")):to_be_truthy()
	expect(page:get_by_role("button", { name = "Reload" }):count()):to_be(0)
end)

test("the browser takes the keys the page does not keep, and the page keeps the ones it listed", function()
	local page = open()
	local web = page:get_by_id("web")
	web:say({ status = "ready" })
	page:click_at(450, 300)
	expect(page:focus().kind):to_be("browser")
	page:press("cmd+t")
	page:type("ab")
	expect(page:browser_keys()):to_equal({ "cmd+t", "a", "b" })
	page:press("cmd+l")
	expect(page:focus().kind):to_be("field")
	expect(#page:browser_keys()):to_be(3)
end)

test("a host that shows no browser tells the page so, once, and the page says it", function()
	local page = open({ browsers = false })
	expect(page:says("This terminal cannot show a browser.")):to_be_truthy()
	expect(page:get_by_id("web"):navigations()):to_equal({})
	expect(page:get_by_role("button", { name = "Reload" }):count()):to_be(0)
end)

test("the find bar is the page's, and the browser is asked to find, to go on and to stop", function()
	local page = open()
	local web = page:get_by_id("web")
	web:say({ status = "ready" })
	expect(page:get_by_id("find"):count()):to_be(0)
	-- The key was kept for the page: it opens the bar and the keyboard is in it.
	page:click_at(450, 300)
	page:press("cmd+f")
	expect(page:focus().kind):to_be("field")
	page:get_by_id("find"):fill("word")
	expect(web:navigations()[2]):to_equal({ command = "find", pattern = "word", case = false })
	web:say({ found = { count = 12, current = 3 } })
	expect(page:says("3 of 12")):to_be_truthy()
	page:press("enter")
	expect(web:navigations()[3]):to_equal({ command = "find_next" })
	page:press("shift+enter")
	expect(web:navigations()[4]):to_equal({ command = "find_previous" })
	web:say({ found = { count = 0 } })
	expect(page:says("No matches")):to_be_truthy()
	page:press("escape")
	expect(web:navigations()[5]):to_equal({ command = "stop_finding" })
	expect(page:get_by_id("find"):count()):to_be(0)
end)

test("the steps of the zoom are the page's, and the browser is asked for the size", function()
	local page = open()
	local web = page:get_by_id("web")
	web:say({ status = "ready" })
	page:click_at(450, 300)
	page:press("cmd+=")
	expect(web:navigations()[2]):to_equal({ zoom = 1.1 })
	web:say({ zoom = 1.1 })
	page:press("cmd+=")
	expect(web:navigations()[3]):to_equal({ zoom = 1.25 })
	web:say({ zoom = 1.25 })
	page:press("cmd+-")
	expect(web:navigations()[4]):to_equal({ zoom = 1.1 })
	web:say({ zoom = 1.5 })
	page:press("cmd+0")
	expect(web:navigations()[5]):to_equal({ zoom = 1 })
	-- None of these keys went to the browser: they are on the page's list.
	expect(page:browser_keys()):to_equal({})
end)

test("a key the browser had no use for comes to the page, which goes back for it", function()
	local page = open()
	local web = page:get_by_id("web")
	web:say({ status = "ready" })
	page:click_at(450, 300)
	page:press("cmd+left")
	expect(page:browser_keys()):to_equal({ "cmd+left" })
	expect(#web:navigations()):to_be(1)
	web:unused_key("cmd+left")
	expect(web:navigations()[2]):to_equal({ command = "back" })
end)

test("a link that opens a window is followed, unless the person asked for it behind the page", function()
	local page = open()
	local web = page:get_by_id("web")
	web:say({ status = "ready" })
	web:open_window("https://example.org/a")
	expect(web:navigations()[2]):to_equal({ go = "https://example.org/a" })
	web:open_window("https://example.org/b", true)
	expect(#web:navigations()):to_be(2)
	expect(page:says("A link to open behind this page: https://example.org/b")):to_be_truthy()
end)
